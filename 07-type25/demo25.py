# Напишите программу, которая перебирает целые числа, бо́льшие
# 1 103 285 717, в порядке возрастания и ищет среди них числа,
# представленные в виде произведения ровно двух простых множителей,
# не обязательно различных, каждый из которых ровно один раз содержит
# в своей записи 16 (16 – идущие подряд друг за другом в указанном порядке
# цифры 1 и 6).
# В ответе в первом столбце таблицы запишите первые 5 найденных чисел
# в порядке возрастания, а во втором столбце – для каждого из них
# соответствующий наименьший найденный множитель.

def prime_divs(n):
    ans = []
    d = 2
    while d**2 <= n:
        while n % d == 0:
            ans.append(d)
            n //= d
        d += 1
    if n > 1: ans.append(n)
    return ans

cnt = 0
n = 1_103_285_717
while cnt < 5:
    res = prime_divs(n)
    if len(res) == 2 and all('16' in str(i) for i in res):
        cnt += 1
        print(n, min(res))
    n += 1