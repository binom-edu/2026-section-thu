# Значение арифметического выражения 7**170 + 7**100 – x, где x – целое
# положительное число, не превышающее 2030, записали в 7-ричной системе
# счисления. Определите наибольшее значение x, при котором в данной
# записи значения арифметического выражения содержится ровно 71 нуль.
# В ответе запишите число в десятичной системе счисления.

def zeros(n):
    ans = 0
    while n:
        if n % 7 == 0:
            ans += 1
        n //= 7
    return ans

for x in range(1, 2031):
    n = 7**170 + 7**100 - x
    if zeros(n) == 71:
        ans = x
print(ans)