# Операнды арифметического выражения записаны в системе счисления
# с основанием 22.
# 27x98876 + 26x51 + 711x5
# В записи чисел переменной x обозначена неизвестная цифра из алфавита
# 22-ричной системы счисления. Определите наименьшее значение x, при
# котором значение данного арифметического выражения кратно 21. Для
# найденного x вычислите частное от деления значения арифметического
# выражения на 21 и укажите его в ответе в десятичной системе счисления.
# Основание системы счисления указывать не нужно.

a, b, c = '27x98876', '26x51', '711x5'
alf = '0123456789abcdefghijkl'
for x in alf:
    n = int(a.replace('x', x), 22) + int(b.replace('x', x), 22) + int(c.replace('x', x), 22)
    if n % 21 == 0: print(n // 21)